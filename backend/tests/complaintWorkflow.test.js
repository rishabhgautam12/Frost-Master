const test = require("node:test");
const assert = require("node:assert/strict");
const mongoose = require("mongoose");
const Complaint = require("../models/Complaint");
const Employee = require("../models/Employee");
const Sale = require("../models/Sale");
const audit = require("../utils/auditLogger");
audit.logActivity = async () => {};
const controller = require("../controllers/complaintController");

test("service ticket lifecycle, validation and preserved reassignment history", async () => {
  const employee1 = { _id:new mongoose.Types.ObjectId(), name:"Technician A", status:"Active" };
  const employee2 = { _id:new mongoose.Types.ObjectId(), name:"Technician B", status:"Active" };
  let stored;
  const originals = { create:Complaint.create, find:Complaint.findById, employee:Employee.findById, sale:Sale.findById };
  Complaint.create = async fields => { stored = new Complaint(fields); await stored.validate(); stored.save = async () => { await stored.validate(); return stored; }; return stored; };
  Complaint.findById = async () => stored;
  Employee.findById = async id => [employee1,employee2].find(e => String(e._id) === String(id));
  async function call(handler, body, admin = true) {
    let code = 200, result;
    await handler({ body, params:{ id:stored?._id }, user:{ _id:new mongoose.Types.ObjectId(), name:"Coordinator", role:admin ? "admin" : "staff" } }, { status(n) { code=n; return this; }, json(data) { result=data; } });
    return { code, ...result };
  }
  try {
    assert.equal((await call(controller.createComplaint, {}, false)).code,403);
    assert.equal((await call(controller.createComplaint, { complaint:"No picture" })).code,400);
    const created = await call(controller.createComplaint, { referenceType:"External", externalComplaintNo:"EMAIL-123", partyName:"Customer", productName:"TV", complaint:"No picture", receivedAt:"2026-01-01T09:00:00Z" });
    assert.equal(created.code,201);
    assert.equal(stored.timeline[0].type,"Received");
    assert.equal(stored.referenceId,undefined);
    const update = (type, extra={}) => call(controller.addTimelineEvent, { type, occurredAt:"2026-01-02T10:00:00Z", notes:"Service update", ...extra });
    assert.equal((await update("Closed", { workDone:"Fixed" })).code,400);
    assert.equal((await update("Assigned", { employee:employee1._id })).success,true);
    assert.equal((await update("Visit Scheduled", { scheduledAt:"invalid" })).code,400);
    assert.equal((await update("Visit Scheduled", { scheduledAt:"2026-01-03T10:00:00Z" })).success,true);
    assert.equal((await update("Visit Scheduled", { notes:"", occurredAt:undefined, scheduledAt:new Date(Date.now()+86400000).toISOString() })).success,true);
    assert.equal((await update("Visit Scheduled", { notes:"", scheduledAt:"" })).code,400);
    assert.equal((await update("Visit Report", { notes:"", workDone:"Checked power" })).success,true);
    assert.equal((await update("Visit Report", { notes:"", workDone:"" })).code,400);
    assert.equal((await update("Visit Report", { problemFound:"Power board fault", workDone:"Diagnosed board", stage:"Waiting for Parts" })).success,true);
    assert.equal((await update("Visit Report", { problemFound:"Power board fault", workDone:"Diagnosed board", stage:"Waiting for Parts", nextAction:"Order replacement board" })).success,true);
    assert.equal(stored.stage,"Waiting for Parts");
    assert.equal((await update("Assigned", { employee:employee2._id, workDone:"Power board diagnosed", nextAction:"Fit replacement board" })).success,true);
    assert.equal(stored.stage,"Waiting for Parts");
    const reassignment = stored.timeline.at(-1);
    assert.equal(reassignment.type,"Reassigned");
    assert.equal(reassignment.previousEmployeeName,"Technician A");
    assert.equal(reassignment.employeeName,"Technician B");
    assert.equal(reassignment.workDone,"Power board diagnosed");
    assert.equal(reassignment.nextAction,"Fit replacement board");
    assert.equal((await update("Assigned", { employee:employee1._id, notes:"" })).success,true);
    assert.equal((await update("Note", { notes:"" })).code,400);
    assert.equal((await update("Closed", { notes:"", workDone:"" })).code,400);
    assert.equal((await update("Closed", { workDone:"Replaced board and tested TV", customerFeedback:"Customer confirmed working" })).success,true);
    assert.equal(stored.status,"Solved");
    assert.equal(stored.resolution,"Replaced board and tested TV");
    assert.equal((await update("Note")).code,400);
    assert.equal((await update("Reopened", { notes:"Problem returned" })).success,true);
    assert.equal(stored.status,"Active");
    assert.equal(stored.resolvedAt,undefined);
    assert.ok(stored.timeline.some(e => e.type==="Closed" && e.workDone==="Replaced board and tested TV"));
    assert.equal((await call(controller.addTimelineEvent,{ type:"Note",notes:"Unauthorized" },false)).code,403);
    const old = new Complaint({ referenceType:"Sale", productName:"TV", complaint:"Old issue", createdAt:new Date("2025-01-01"), status:"Solved", resolution:"Earlier repair", resolvedAt:new Date("2025-01-02") });
    assert.equal(old.receivedAt,undefined);
    stored=old; stored.save=async () => stored;
    assert.equal((await update("Reopened")).success,true);
    assert.deepEqual(stored.timeline.map(e => e.type),["Received","Closed","Reopened"]);
    const productId = new mongoose.Types.ObjectId();
    const sale = { _id:new mongoose.Types.ObjectId(), invoiceNo:"INV-TEST-123", date:new Date("2026-01-01"), customer:{ name:"Invoice customer" }, items:[{ product:{ _id:productId, name:"Invoice TV" }, productName:"Invoice TV", description:"65 inch" }] };
    Sale.findById = () => ({ populate() { return this; }, then(resolve) { return Promise.resolve(sale).then(resolve); } });
    const body = { referenceType:"Sale", referenceId:sale._id, product:productId, complaint:"Screen issue", receivedAt:"2026-01-02", partyName:"Untrusted name", productName:"Untrusted product" };
    assert.equal((await call(controller.createComplaint,{ ...body,product:new mongoose.Types.ObjectId() })).code,400);
    assert.equal((await call(controller.createComplaint,body)).code,201);
    assert.equal(String(stored.referenceId),String(sale._id));
    assert.equal(stored.invoiceNo,"INV-TEST-123");
    assert.equal(stored.productName,"Invoice TV");
    assert.equal(stored.partyName,"Invoice customer");
  } finally { Complaint.create=originals.create; Complaint.findById=originals.find; Employee.findById=originals.employee; Sale.findById=originals.sale; }
});
